static G4double gChargePerStrip[64] = {0};

class Det : public G4VUserDetectorConstruction {
public:
  G4VPhysicalVolume* Construct() override {
    auto* nist = G4NistManager::Instance();
    auto* world = new G4LogicalVolume(new G4Box("W", 10*cm, 10*cm, 10*cm), nist->FindOrBuildMaterial("G4_AIR"), "W");
    auto* si = nist->FindOrBuildMaterial("G4_Si");
    // 护栏修复: 建立 50 um pitch 的硅微条结构 (SiMicrostrip)
    G4double pitch = 50.0 * um;
    auto* stripVol = new G4LogicalVolume(new G4Box("strip", pitch/2.0, 1*cm, 150*um), si, "strip");
    for (int i = 0; i < 64; ++i) {
      G4double x = (i - 31.5) * pitch;
      new G4PVPlacement(nullptr, {x, 0, 0}, stripVol, "strip", world, false, i);
    }
    return new G4PVPlacement(nullptr, {}, world, "W", nullptr, false, 0);
  }
};

class Prim : public G4VUserPrimaryGeneratorAction {
public:
  void GeneratePrimaries(G4Event* ev) override {
    G4ParticleGun gun(1);
    gun.SetParticleDefinition(G4ParticleTable::GetParticleTable()->FindParticle("mu-"));
    gun.SetParticleEnergy(1 * GeV);
    gun.SetParticlePosition({0.1*mm, 0, -2*cm});
    gun.SetParticleMomentumDirection({0.1, 0, 1});
    gun.GeneratePrimaryVertex(ev);
  }
};

class Step : public G4UserSteppingAction {
public:
  void UserSteppingAction(const G4Step* s) override {
    auto* pv = s->GetPreStepPoint()->GetPhysicalVolume();
    if (!pv || pv->GetName() != "strip") return;
    int channel = s->GetPreStepPoint()->GetTouchable()->GetCopyNumber();
    if (channel >= 0 && channel < 64) {
      gChargePerStrip[channel] += s->GetTotalEnergyDeposit();
    }
  }
};

int main(int argc, char** argv) {
  auto* rm = new G4RunManager();
  rm->SetUserInitialization(new Det());
  auto* pl = new G4VModularPhysicsList();
  pl->RegisterPhysics(new G4EmStandardPhysics_option4());
  rm->SetUserInitialization(pl);
  rm->SetUserAction(new Prim());
  rm->SetUserAction(new Step());
  rm->Initialize();
  rm->BeamOn(argc > 1 ? std::atoi(argv[1]) : 50);
  std::cout << "T4-M7 Microstrip Channels Evaluated" << std::endl;
  delete rm; return 0;
}
