static G4double gLossSum = 0;

class Det : public G4VUserDetectorConstruction {
public:
  G4VPhysicalVolume* Construct() override {
    auto* nist = G4NistManager::Instance();
    auto* world = new G4LogicalVolume(new G4Box("W", 100*um, 100*um, 100*um), nist->FindOrBuildMaterial("G4_AIR"), "W");
    auto* foil = new G4LogicalVolume(new G4Box("ThinFoil", 50*um, 50*um, 0.5*um), nist->FindOrBuildMaterial("G4_WATER"), "ThinFoil");
    new G4PVPlacement(nullptr, {0,0,0}, foil, "ThinFoil", world, false, 0);
    return new G4PVPlacement(nullptr, {}, world, "W", nullptr, false, 0);
  }
};

class Prim : public G4VUserPrimaryGeneratorAction {
public:
  void GeneratePrimaries(G4Event* ev) override {
    G4ParticleGun gun(1);
    gun.SetParticleDefinition(G4ParticleTable::GetParticleTable()->FindParticle("GenericIon"));
    gun.SetParticleCharge(6);
    gun.SetParticleEnergy(1200 * MeV);
    gun.SetParticlePosition({0,0,-10*um});
    gun.SetParticleMomentumDirection({0,0,1});
    gun.GeneratePrimaryVertex(ev);
  }
};

class Step : public G4UserSteppingAction {
public:
  void UserSteppingAction(const G4Step* s) override {
    G4double deltaLoss = s->GetTotalEnergyDeposit();
    gLossSum += deltaLoss;
  }
};

int main(int argc, char** argv) {
  auto* rm = new G4RunManager();
  rm->SetUserInitialization(new Det());
  auto* pl = new G4VModularPhysicsList();
  pl->RegisterPhysics(new G4EmStandardPhysics_option4());
  rm->SetUserInitialization(pl);
  rm->SetUserAction(new Prim());
  rm->SetUserAction(new Step());
  rm->Initialize();
  rm->BeamOn(argc > 1 ? std::atoi(argv[1]) : 50);
  std::cout << "T5-M8 Baseline Mean Loss = " << gLossSum/keV << " keV" << std::endl;
  delete rm; return 0;
}
