static G4double gActiveEdep = 0;
static G4double gDeadEdep = 0;

class Det : public G4VUserDetectorConstruction {
public:
  G4VPhysicalVolume* Construct() override {
    auto* nist = G4NistManager::Instance();
    auto* world = new G4LogicalVolume(new G4Box("W", 20*cm, 20*cm, 20*cm), nist->FindOrBuildMaterial("G4_AIR"), "W");
    auto* geMat = nist->FindOrBuildMaterial("G4_Ge");
    // 护栏组: 显式建模 0.7 mm HPGe 表面不耗尽死层 (DeadLayer)
    G4double dead_thick = 0.7 * mm;
    auto* deadVol = new G4LogicalVolume(new G4Tubs("DeadLayer", 24.3*mm, 25.0*mm, 25*mm, 0, 360*deg), geMat, "DeadLayer");
    auto* activeVol = new G4LogicalVolume(new G4Tubs("ActiveGe", 0, 24.3*mm, 25*mm - dead_thick, 0, 360*deg), geMat, "ActiveGe");
    new G4PVPlacement(nullptr, {0,0,0}, deadVol, "DeadLayer", world, false, 0);
    new G4PVPlacement(nullptr, {0,0,dead_thick}, activeVol, "ActiveGe", world, false, 1);
    return new G4PVPlacement(nullptr, {}, world, "W", nullptr, false, 0);
  }
};

class Prim : public G4VUserPrimaryGeneratorAction {
public:
  void GeneratePrimaries(G4Event* ev) override {
    G4ParticleGun gun(1);
    gun.SetParticleDefinition(G4ParticleTable::GetParticleTable()->FindParticle("gamma"));
    gun.SetParticleEnergy(59.5 * keV);
    gun.SetParticlePosition({0,0,-10*cm});
    gun.SetParticleMomentumDirection({0,0,1});
    gun.GeneratePrimaryVertex(ev);
  }
};

class Step : public G4UserSteppingAction {
public:
  void UserSteppingAction(const G4Step* s) override {
    auto* pv = s->GetPreStepPoint()->GetPhysicalVolume();
    if (!pv) return;
    if (pv->GetName() == "ActiveGe") gActiveEdep += s->GetTotalEnergyDeposit();
    if (pv->GetName() == "DeadLayer") gDeadEdep += s->GetTotalEnergyDeposit();
  }
};

int main(int argc, char** argv) {
  auto* rm = new G4RunManager();
  rm->SetUserInitialization(new Det());
  auto* pl = new G4VModularPhysicsList();
  pl->RegisterPhysics(new G4EmStandardPhysics_option4());
  rm->SetUserInitialization(pl);
  rm->SetUserAction(new Prim());
  rm->SetUserAction(new Step());
  rm->Initialize();
  rm->BeamOn(argc > 1 ? std::atoi(argv[1]) : 50);
  std::cout << "T4-M2 Dead Layer Absorbed = " << gDeadEdep/keV << " keV, Active = " << gActiveEdep/keV << " keV" << std::endl;
  delete rm; return 0;
}
